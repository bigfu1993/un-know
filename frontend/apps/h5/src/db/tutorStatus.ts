/**
 * 家教试课/正式雇佣全流程状态的唯一标准，所有家教卡片（进行中卡片、兼职列表卡片、
 * 试课申请列表等）判断和展示状态时只应引用这里的枚举值，不再各自散落同义的字符串字面量。
 * 成员按业务实际流转顺序排列：发布招募 → 试课申请与确认 → 试课中 → 试课结束与结果处理 →
 * 正式雇佣确认与日程 → 正式服务进行中 → 服务结束与结算 → 结算完成；不在主流程分支上、
 * 代表退出/终止的状态统一收在末尾。
 */
export enum TutorStatus {
  /** 家教需求发布中（招募中）。 */
  Recruiting = "发布中",

  /** 学生已提交试课申请，等待家长处理。 */
  ApplicationPending = "申请试课中",
  /** 家长已提交试课安排后，学生端等待确认流程的展示状态。 */
  TrialConfirming = "试课日程确认中",
  /** 学生已确认家长安排后，试课正在进行的展示状态。 */
  Trialing = "试课中",
  /** 学生提交结束试课后，等待家长确认的展示状态。 */
  TrialEndConfirming = "结束试课确认中",
  /** 家长处理试课是否正式雇佣时的展示状态。 */
  TrialResultProcessing = "试课结果处理",
  /** 学生已确认试课费用，等待家长决定是否正式雇佣的状态。 */
  TrialSettledServicePending = "试课已结算",

  /** 家长已发起正式雇佣，等待学生确认的展示状态。 */
  ServiceConfirming = "正式雇佣确认中",
  /** 学生同意正式雇佣后，等待家长提交正式雇佣日程的展示状态。 */
  ServiceSchedulePending = "正式雇佣日程确认中",
  /** 旧版家长提交兼职日程后，等待学生确认的展示状态。 */
  ServiceScheduleConfirming = "兼职日程确认中",

  /** 家长提交正式雇佣日程后的正式雇佣状态。 */
  FormalService = "正式雇佣",
  /** 学生同意正式雇佣后，家教需求主任务进入进行中。 */
  DemandInProgress = "进行中",

  /** 学生发起正式服务结束后，等待家长提交结算金额的状态。 */
  ServiceEndConfirming = "结束兼职确认中",
  /** 家长端主任务在学生申请结束正式服务后的第二状态展示。 */
  ServiceEndRequested = "申请结束中",
  /** 家教或试课结算等待学生确认的展示状态。 */
  SettlementConfirming = "结算确认中",
  /** 学生要求修改结算金额后的展示状态。 */
  SettlementRevising = "结算修改中",
  /** 家教系统计算结算金额时的展示状态。 */
  SystemSettling = "系统结算中",
  /** 通用已结束终态，覆盖家教需求和试课申请两种场景。 */
  Ended = "已结束",

  // 以下为不在主流程分支上、代表退出或终止的状态。

  /** 家长不正式雇佣且继续发布后的试课终态。 */
  TrialEnded = "试课已结束",
  /** 家长拒绝试课后的学生端失效状态。 */
  Rejected = "已失效",
  /** 学生拒绝正式雇佣后的终态。 */
  ServiceInvalid = "正式雇佣失效",
  /** 通用已取消终态，覆盖家教需求和试课申请两种场景。 */
  Cancelled = "已取消"
}
